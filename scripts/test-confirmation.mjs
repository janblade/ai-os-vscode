import { chromium } from 'playwright-core';
import { strict as assert } from 'node:assert';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
const { confirmationHtml } = createRequire(import.meta.url)('../.test-build/src/core/confirmation.js');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 720, height: 850 } });
  const errors = []; page.on('pageerror', error => errors.push(String(error)));
  const html = confirmationHtml('Allow this tool?', '<img src=x onerror="window.pwned=true">\nRepository: isolated fixture\nCommand: node --test', ['Allow once', 'Deny'], 'fixture').replace('</head>', '<script nonce="fixture">window.responses=[];window.acquireVsCodeApi=()=>({postMessage:message=>window.responses.push(message)});</script></head>');
  await page.goto('about:blank'); await page.setContent(html);
  assert.equal(await page.locator('img').count(), 0);
  assert.equal(await page.locator('#cancel').evaluate(element => element === document.activeElement), true);
  await mkdir('.vscode-test/artifacts', { recursive: true });
  await page.screenshot({ path: '.vscode-test/artifacts/approval-card.png', fullPage: true });
  await page.getByRole('button', { name: 'Allow once', exact: true }).click();
  assert.deepEqual(await page.evaluate(() => window.responses), [{ type: 'confirmation', choice: 0 }]);
  assert.equal(await page.locator('button:not([disabled])').count(), 0);
  await page.goto('about:blank'); await page.setContent(html); await page.keyboard.press('Escape');
  assert.deepEqual(await page.evaluate(() => window.responses), [{ type: 'confirmation', choice: null }]);
  await page.goto('about:blank'); await page.setContent(html); await page.getByRole('button', { name: 'Deny', exact: true }).click();
  assert.deepEqual(await page.evaluate(() => window.responses), [{ type: 'confirmation', choice: 1 }]);
  await page.setViewportSize({ width: 320, height: 700 }); await page.goto('about:blank'); await page.setContent(html);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.keyboard.press('Enter');
  assert.deepEqual(await page.evaluate(() => window.responses), [{ type: 'confirmation', choice: null }]);
  const question = confirmationHtml('Baseline decision', 'Live runtime unavailable', [], 'fixture', true).replace('</head>', '<script nonce="fixture">window.responses=[];window.acquireVsCodeApi=()=>({postMessage:message=>window.responses.push(message)});</script></head>');
  await page.goto('about:blank'); await page.setContent(question);
  await page.getByRole('button', { name: 'Send reply' }).click();
  assert.deepEqual(await page.evaluate(() => window.responses), []);
  await page.getByLabel('Your reply').fill('Try focused regression tests first');
  await page.getByRole('button', { name: 'Send reply' }).click();
  assert.deepEqual(await page.evaluate(() => window.responses), [{type:'question',answer:'Try focused regression tests first'}]);
  assert.equal(await page.locator('button:not([disabled])').count(), 0);
  await page.goto('about:blank'); await page.setContent(question); await page.keyboard.press('Escape');
  assert.deepEqual(await page.evaluate(() => window.responses), [{type:'question',answer:null}]);
  const decision = confirmationHtml('How should Build continue?', 'Live baseline is unverified', ['Continue investigation','Prepare revised plan'], 'fixture', true, {options:[{label:'Continue investigation',description:'Try read-only diagnostics'},{label:'Prepare revised plan',description:'Propose an amendment for review'}],recommendation:'Try available checks first. Tool permissions remain separate.',cancelLabel:'Stop run'}).replace('</head>', '<script nonce="fixture">window.responses=[];window.acquireVsCodeApi=()=>({postMessage:message=>window.responses.push(message)});</script></head>');
  await page.goto('about:blank'); await page.setContent(decision);
  assert.equal(await page.getByLabel('Your reply').isVisible(),false);
  await page.getByRole('button',{name:/Prepare revised plan/}).click();
  assert.deepEqual(await page.evaluate(()=>window.responses),[{type:'question',choice:1}]);
  assert.equal(await page.locator('button:not([disabled])').count(),0);
  await page.goto('about:blank'); await page.setContent(decision);
  await page.getByText('Give a different instruction',{exact:true}).click();
  await page.getByLabel('Your reply').fill('Inspect the existing logs first');
  await page.getByRole('button',{name:'Send reply',exact:true}).click();
  assert.deepEqual(await page.evaluate(()=>window.responses),[{type:'question',answer:'Inspect the existing logs first'}]);
  await page.goto('about:blank'); await page.setContent(decision);
  await page.getByRole('button',{name:'Stop run',exact:true}).click();
  assert.deepEqual(await page.evaluate(()=>window.responses),[{type:'question',answer:null}]);
  await page.goto('about:blank'); await page.setContent(decision);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:'.vscode-test/artifacts/blocked-run-decision.png',fullPage:true});
  assert.deepEqual(errors, []);
  console.log('Approval card browser checks passed: explicit allow/deny, Escape/Enter cancel, no double response, inert content and narrow layout.');
} finally { await browser.close(); }
